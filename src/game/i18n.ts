export const translations: Record<Language, typeof en> = { en, de };

export function translateServerMessage(sender: string, message: string, language: Language): string {
  if (["System", "!fs|!freestyle", "!bug", "!h|!help"].includes(sender)) {
    return translations[language].notices[message] ?? message;
  }
  return message;
}

export function translateError(message: string, language: Language): string {
  return translations[language].errors[message] ?? message;
}
