export type Language = "en" | "de";

/** Use the browser's primary preference; unsupported languages fall back to English. */
export function selectLanguage(language?: string | null): Language {
  return language?.trim().split(/[-_]/)[0]?.toLowerCase() === "de" ? "de" : "en";
}

export function browserLanguage(): Language {
  return selectLanguage(navigator.languages?.[0] || navigator.language);
}

